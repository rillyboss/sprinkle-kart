/**
 * Offline app shell: generates dist/sw.js after every production build. OWNER: mobile platform.
 * No Workbox — a small hand-written worker (swSource below) with the build's file list baked in.
 *
 *   precache   every file of the build (index.html, JS/CSS chunks, icons, self-hosted fonts, manifest) —
 *              cached under `sprinkle-kart-<build id>` when the worker installs, so local play works offline
 *   page loads NETWORK-FIRST: online, the page is always the newest deploy (online peers never get a stale
 *              build, NETWORKING.md §7.2); offline (fetch fails), the cached index.html
 *   other GETs cache-first (the hashed chunks never change), falling back to the network (and caching it)
 *   updates    a new worker waits; the page shows "New version — tap to update" (src/platform/pwa.js) and
 *              sends SKIP_WAITING; old caches are deleted on activate. The very first install takes over at once.
 *   GET_VERSION message → replies { build } (the page compares it with its own __SK_BUILD__)
 * Everything is relative to the worker's scope, so it works at / and under the GitHub Pages sub-path.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

/** Files never precached (the worker itself, source maps, OS junk). */
export const PRECACHE_EXCLUDE = [/^sw\.js$/, /\.map$/, /(^|\/)\.DS_Store$/, /(^|\/)Thumbs\.db$/];

/** Every file under dir, as forward-slash paths relative to dir, sorted. */
export function listFiles(dir, base = dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listFiles(full, base));
    else out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

/** The precache list for a build directory: [{ url: './x', rev }] (rev = content hash, changes with the file). */
export function precacheEntries(dir, exclude = PRECACHE_EXCLUDE) {
  return listFiles(dir)
    .filter((f) => !exclude.some((re) => re.test(f)))
    .map((f) => ({ url: `./${f}`, rev: createHash('sha1').update(readFileSync(path.join(dir, f))).digest('hex').slice(0, 10) }));
}

/** A version string for the whole precache (changes whenever any file changes). */
export function precacheVersion(entries, buildId = 'dev') {
  const h = createHash('sha1');
  for (const e of entries) h.update(`${e.url}@${e.rev}\n`);
  return `${buildId}-${h.digest('hex').slice(0, 8)}`;
}

/**
 * The service worker source.
 * @param {{ version: string, build: string, urls: string[] }} o
 */
export function swSource({ version, build, urls }) {
  return `/* Sprinkle Kart service worker — generated by build/pwa.js. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const BUILD = ${JSON.stringify(build)};
const PREFIX = 'sprinkle-kart-';
const CACHE = PREFIX + VERSION;
const PRECACHE = ${JSON.stringify(urls)};
const scoped = (u) => new URL(u, self.registration.scope).href;
const INDEX = scoped('./index.html');

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE.map((u) => new Request(scoped(u), { cache: 'reload' })))));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  const type = event.data && event.data.type;
  if (type === 'SKIP_WAITING') self.skipWaiting();
  else if (type === 'GET_VERSION' && event.ports && event.ports[0]) event.ports[0].postMessage({ build: BUILD, version: VERSION });
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !req.url.startsWith(self.registration.scope)) return;
  if (req.mode === 'navigate') {
    // network first: online players always get the newest deploy; offline → the cached page
    event.respondWith((async () => {
      try {
        const res = await fetch(req);
        if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(INDEX, copy)).catch(() => {}); }
        return res;
      } catch (err) {
        return (await caches.match(INDEX)) || (await caches.match(req, { ignoreSearch: true })) || Response.error();
      }
    })());
    return;
  }
  event.respondWith((async () => {
    const hit = await caches.match(req);
    if (hit) return hit;
    const res = await fetch(req);
    if (res && res.ok && res.type === 'basic') { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {}); }
    return res;
  })());
});
`;
}

/**
 * The Vite plugin: writes <outDir>/sw.js once the build (including the public/ copy) is on disk.
 * @param {{ buildId?: () => string }} [opts]
 */
export function pwaServiceWorker({ buildId = () => 'dev' } = {}) {
  let outDir = null;
  let isBuild = false;
  return {
    name: 'sk-pwa-service-worker',
    apply: 'build',
    configResolved(config) {
      isBuild = config.command === 'build';
      outDir = path.resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      if (!isBuild || !outDir) return;
      const entries = precacheEntries(outDir);
      const build = buildId();
      const version = precacheVersion(entries, build);
      writeFileSync(path.join(outDir, 'sw.js'), swSource({ version, build, urls: entries.map((e) => e.url) }));
      console.log(`[pwa] sw.js: ${entries.length} files precached (version ${version})`);
    },
  };
}
